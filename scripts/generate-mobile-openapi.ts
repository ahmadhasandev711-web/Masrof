/**
 * Generates contracts/mobile/openapi.yaml from Zod mobile contracts.
 * Usage: npx tsx scripts/generate-mobile-openapi.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { toJSONSchema } from "zod";
import { mobileContractSchemas, mobileOpenApiPaths } from "../contracts/mobile/registry";

type JsonSchema = Record<string, unknown>;

function toComponentSchema(schema: unknown): JsonSchema {
  const raw = toJSONSchema(schema as never, { target: "draft-7" }) as JsonSchema;
  // OpenAPI components should not carry $schema
  const { $schema: _drop, ...rest } = raw;
  return rest;
}

const components: Record<string, JsonSchema> = {};
for (const [name, schema] of Object.entries(mobileContractSchemas)) {
  components[name] = toComponentSchema(schema);
}

const paths: Record<string, Record<string, unknown>> = {};
for (const entry of mobileOpenApiPaths) {
  paths[entry.path] ??= {};
  paths[entry.path][entry.method] = {
    operationId: entry.operationId,
    summary: entry.summary,
    tags: ["mobile"],
    responses: {
      "200": {
        description: "Success",
        content: {
          "application/json": {
            schema: { $ref: `#/components/schemas/${entry.responseSchema}` },
          },
        },
      },
      "201": {
        description: "Created (when applicable)",
        content: {
          "application/json": {
            schema: { $ref: `#/components/schemas/${entry.responseSchema}` },
          },
        },
      },
      "4XX": {
        description: "Client / auth / plan error",
        content: {
          "application/json": {
            schema: { $ref: "#/components/schemas/MobileError" },
          },
        },
      },
    },
  };
}

const doc = {
  openapi: "3.1.0",
  info: {
    title: "Sanadat Mobile API",
    version: "1.0.0",
    description:
      "Contract for /api/mobile. TypeScript types are inferred from Zod in contracts/mobile. This file is generated — do not edit by hand.",
  },
  servers: [{ url: "/", description: "Same origin as the web app" }],
  paths,
  components: {
    schemas: components,
    securitySchemes: {
      sessionCookie: {
        type: "apiKey",
        in: "cookie",
        name: "better-auth.session_token",
        description: "Better Auth session cookie (or __Secure- prefixed in production)",
      },
    },
  },
  security: [{ sessionCookie: [] }],
};

function toYaml(value: unknown, indent = 0): string {
  const pad = "  ".repeat(indent);
  if (value === null) return "null";
  if (typeof value === "string") {
    if (value.includes("\n") || /[:#{}[\],&*?|>!%@`]/.test(value)) {
      return JSON.stringify(value);
    }
    return value;
  }
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return value
      .map((item) => {
        if (item !== null && typeof item === "object") {
          const nested = toYaml(item, indent + 1);
          return `${pad}- ${nested.replace(/^\s+/, "")}`;
        }
        return `${pad}- ${toYaml(item)}`;
      })
      .join("\n");
  }
  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) return "{}";
    return entries
      .map(([k, v]) => {
        if (v !== null && typeof v === "object") {
          return `${pad}${k}:\n${toYaml(v, indent + 1)}`;
        }
        return `${pad}${k}: ${toYaml(v)}`;
      })
      .join("\n");
  }
  return JSON.stringify(value);
}

const outPath = resolve(process.cwd(), "contracts/mobile/openapi.yaml");
writeFileSync(outPath, `# Generated by scripts/generate-mobile-openapi.ts\n${toYaml(doc)}\n`, "utf8");
console.log(`Wrote ${outPath}`);
