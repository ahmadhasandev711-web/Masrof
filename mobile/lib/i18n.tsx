type TranslationsType = typeof translations.ar;

interface I18nContextType {
  locale: AppLocale;
  isRTL: boolean;
  t: TranslationsType;
  setLocale: (locale: AppLocale) => Promise<void>;
  toggleLocale: () => Promise<void>;
}

const I18nContext = createContext<I18nContextType>({
  locale: "ar",
  isRTL: true,
  t: translations.ar,
  setLocale: async () => {},
  toggleLocale: async () => {},
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>("ar");

  useEffect(() => {
    SecureStore.getItemAsync(LOCALE_KEY).then((saved) => {
      if (saved === "en" || saved === "ar") {
        setLocaleState(saved);
        setFormatLocale(saved);
      }
    });
  }, []);

  const setLocale = async (newLocale: AppLocale) => {
    setLocaleState(newLocale);
    setFormatLocale(newLocale);
    await SecureStore.setItemAsync(LOCALE_KEY, newLocale);
  };

  const toggleLocale = async () => {
    const target: AppLocale = locale === "ar" ? "en" : "ar";
    await setLocale(target);
  };

  const isRTL = locale === "ar";
  const t = (locale === "en" ? translations.en : translations.ar) as TranslationsType;

  return (
    <I18nContext.Provider value={{ locale, isRTL, t, setLocale, toggleLocale }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
